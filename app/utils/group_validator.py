import re

# Номенклатура шифрування академічних груп: ЛЛ-ттЦЦррх
# Для ФІОТ: перша літера обов'язково 'І' (або латинська 'I', яку нормалізуємо)
# Друга літера: кафедра/ОП (кирилична літера або відповідна латинська при випадковій розкладці)
# 3-й символ: обов'язково дефіс '-'
# Суфікс1: форма навчання (з, п, зп, в, о) - необов'язково
# Цифри: 1-2 цифри (рік вступу та номер групи)
# Суфікс2: освітній рівень (мп, мн, ф) - необов'язково
# Суфікс3: специфіка (і, а, д) - необов'язково

# Загальний шаблон академічної групи КПІ (будь-який факультет)
KPI_GENERAL_PATTERN = re.compile(
    r"^[А-ЯІЇЄҐA-Za-z]{2}[-\u2014\u2013][а-яіїєґa-z]{0,2}\d{1,2}[а-яіїєґa-z]{0,3}$",
    re.IGNORECASE
)

# Шаблон групи ФІОТ (перша літера - кирилична І або латинська I)
FIOT_GROUP_PATTERN = re.compile(
    r"^[ІI][А-ЯІЇЄҐA-Za-z][-\u2014\u2013][а-яіїєґa-z]{0,2}\d{1,2}[а-яіїєґa-z]{0,3}$",
    re.IGNORECASE
)


def normalize_group_name(raw_group: str) -> str:
    """
    Нормалізує шифр групи: видаляє пробіли, замінює тире на '-',
    переводить першу латинську I на українську І та приводить до верхнього регістру.
    """
    if not raw_group:
        return ""

    cleaned = raw_group.strip().replace(" ", "")
    cleaned = re.sub(r"[—–−]", "-", cleaned)

    if cleaned and cleaned[0] in ("I", "i"):
        cleaned = "І" + cleaned[1:]

    return cleaned.upper()


def validate_fiot_group(raw_group: str) -> tuple[bool, str, str]:
    """
    Валідує групу на належність до ФІОТ згідно з номенклатурою КПІ.

    Повертає кортеж:
    (is_valid: bool, normalized_group: str, error_message: str)
    """
    if not raw_group:
        return False, "", "❌ Будь ласка, введи шифр своєї групи."

    # Перевірка на наявність пробілів (правило 3: шифр групи не містить «пробілів»)
    if " " in raw_group.strip():
        return False, "", (
            "❌ <b>Шифр групи не повинен містити пробілів.</b>\n"
            "Приклад правильного запису: <b>ІП-55</b> або <b>ІС-41</b>"
        )

    norm = normalize_group_name(raw_group)

    # 1. Перевірка на відповідність правилам ФІОТ
    if FIOT_GROUP_PATTERN.match(norm):
        return True, norm, ""

    # 2. Якщо це валідний шифр КПІ, але іншого факультету (не починається з І)
    if KPI_GENERAL_PATTERN.match(norm):
        return False, norm, (
            "❌ <b>Реєстрація доступна тільки для студентів ФІОТ!</b>\n\n"
            "Всі академічні групи нашого факультету починаються з літери <b>«І»</b> "
            "(наприклад: <b>ІП-55</b>, <b>ІС-41</b>, <b>ІО-32</b>, <b>ІА-21</b>).\n\n"
            "Якщо ти студент ФІОТ і сталася помилка — будь ласка, перевір введені дані."
        )

    # 3. Якщо шифр взагалі не відповідає номенклатурі академічних груп
    return False, norm, (
        "❌ <b>Некоректний формат групи.</b>\n\n"
        "Згідно з номенклатурою КПІ, шифр академічної групи складається з:\n"
        "• двох літер (для ФІОТ перша літера обов'язково <b>«І»</b>)\n"
        "• розділового дефісу <b>«-»</b> (без пробілів)\n"
        "• двох цифр курсу та номера групи\n\n"
        "<i>Приклади:</i> <b>ІП-55</b>, <b>ІС-41</b>, <b>ІО-з61мп</b>"
    )


def is_fiot_group(group_name: str) -> bool:
    """
    Перевіряє, чи є група групою ФІОТ (для фільтрації існуючих реєстрацій).
    """
    if not group_name or group_name == "-":
        return False
    norm = normalize_group_name(group_name)
    return bool(FIOT_GROUP_PATTERN.match(norm))
